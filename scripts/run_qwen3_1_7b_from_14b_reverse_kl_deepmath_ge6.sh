#!/usr/bin/env bash
# Qwen3-1.7B <- Qwen3-14B on-policy Reverse-KL distillation on DeepMath difficulty>=6.

set -euo pipefail

STUDENT_MODEL=/storage/yukaichengLab/share/model/Qwen3-1.7B
TEACHER_MODEL=/storage/yukaichengLab/share/model/Qwen3-14B
DATA_DIR=${DATA_DIR:-/storage/yukaichengLab/wangxin/test_eiloeo/opd_data/deepmath_ge6_opd}
TRAIN_FILE=${TRAIN_FILE:-${DATA_DIR}/train.parquet}
VAL_FILE=${VAL_FILE:-${DATA_DIR}/test_1000.parquet}
CHECKPOINT_DIR=${CHECKPOINT_DIR:-/storage/yukaichengLab/wangxin/test_eiloeo/opd_checkpoints/qwen3_1_7b_from_14b_reverse_kl_deepmath_ge6}

TRAIN_GPUS=4
TEACHER_GPUS=4
TRAIN_BATCH_SIZE=${TRAIN_BATCH_SIZE:-64}
PPO_MINI_BATCH_SIZE=${PPO_MINI_BATCH_SIZE:-64}
TOTAL_EPOCHS=${TOTAL_EPOCHS:-1}
SAVE_FREQ=${SAVE_FREQ:-25}
MAX_PROMPT_LENGTH=695
MAX_RESPONSE_LENGTH=40264
MAX_MODEL_LEN=40960
MAX_TOKENS_PER_GPU=45056
SEED=20260810

python -m verl.trainer.main_ppo \
  algorithm.adv_estimator=grpo \
  algorithm.use_kl_in_reward=False \
  data.train_files="['${TRAIN_FILE}']" \
  data.val_files="['${VAL_FILE}']" \
  data.train_batch_size=${TRAIN_BATCH_SIZE} \
  data.max_prompt_length=${MAX_PROMPT_LENGTH} \
  data.max_response_length=${MAX_RESPONSE_LENGTH} \
  data.filter_overlong_prompts=True \
  data.filter_overlong_prompts_workers=8 \
  data.truncation=error \
  data.shuffle=True \
  data.seed=${SEED} \
  +data.apply_chat_template_kwargs.enable_thinking=True \
  actor_rollout_ref.model.path="${STUDENT_MODEL}" \
  actor_rollout_ref.model.use_remove_padding=False \
  +actor_rollout_ref.model.override_config.attn_implementation=sdpa \
  actor_rollout_ref.model.enable_gradient_checkpointing=True \
  actor_rollout_ref.actor.strategy=fsdp \
  actor_rollout_ref.actor.optim.lr=1e-6 \
  actor_rollout_ref.actor.optim.lr_scheduler_type=constant \
  actor_rollout_ref.actor.optim.lr_warmup_steps_ratio=0.0 \
  actor_rollout_ref.actor.optim.weight_decay=0.01 \
  actor_rollout_ref.actor.optim.clip_grad=1.0 \
  actor_rollout_ref.actor.ppo_mini_batch_size=${PPO_MINI_BATCH_SIZE} \
  actor_rollout_ref.actor.ppo_micro_batch_size_per_gpu=1 \
  actor_rollout_ref.actor.ppo_epochs=1 \
  actor_rollout_ref.actor.loss_agg_mode=token-mean \
  actor_rollout_ref.actor.use_dynamic_bsz=True \
  actor_rollout_ref.actor.ppo_max_token_len_per_gpu=${MAX_TOKENS_PER_GPU} \
  +actor_rollout_ref.actor.ppo_infer_max_token_len_per_gpu=${MAX_TOKENS_PER_GPU} \
  actor_rollout_ref.actor.use_torch_compile=False \
  actor_rollout_ref.actor.fsdp_config.param_offload=True \
  actor_rollout_ref.actor.fsdp_config.optimizer_offload=True \
  actor_rollout_ref.actor.checkpoint.save_contents="['model','optimizer','extra','hf_model']" \
  actor_rollout_ref.actor.checkpoint.load_contents="['model','optimizer','extra']" \
  actor_rollout_ref.rollout.name=vllm \
  actor_rollout_ref.rollout.tensor_model_parallel_size=1 \
  actor_rollout_ref.rollout.gpu_memory_utilization=0.35 \
  actor_rollout_ref.rollout.n=1 \
  actor_rollout_ref.rollout.seed=${SEED} \
  actor_rollout_ref.rollout.temperature=1.0 \
  actor_rollout_ref.rollout.top_p=1.0 \
  actor_rollout_ref.rollout.top_k=-1 \
  actor_rollout_ref.rollout.do_sample=True \
  actor_rollout_ref.rollout.ignore_eos=False \
  actor_rollout_ref.rollout.enforce_eager=True \
  actor_rollout_ref.rollout.max_num_seqs=32 \
  actor_rollout_ref.rollout.max_num_batched_tokens=32768 \
  actor_rollout_ref.rollout.max_model_len=${MAX_MODEL_LEN} \
  actor_rollout_ref.rollout.log_prob_use_dynamic_bsz=True \
  actor_rollout_ref.rollout.log_prob_max_token_len_per_gpu=${MAX_TOKENS_PER_GPU} \
  trainer.n_gpus_per_node=${TRAIN_GPUS} \
  trainer.nnodes=1 \
  trainer.use_v1=False \
  trainer.total_epochs=${TOTAL_EPOCHS} \
  trainer.val_before_train=False \
  trainer.test_freq=-1 \
  trainer.save_freq=${SAVE_FREQ} \
  trainer.default_local_dir="${CHECKPOINT_DIR}" \
  trainer.max_actor_ckpt_to_keep=3 \
  trainer.resume_mode=auto \
  trainer.logger='["console"]' \
  trainer.project_name=qwen3_opd_reverse_kl \
  trainer.experiment_name=qwen3_1_7b_from_14b_reverse_kl_deepmath_ge6 \
  distillation.enabled=True \
  distillation.n_gpus_per_node=${TEACHER_GPUS} \
  distillation.nnodes=1 \
  distillation.teacher_models.teacher_model.model_path="${TEACHER_MODEL}" \
  distillation.teacher_models.teacher_model.inference.name=vllm \
  distillation.teacher_models.teacher_model.inference.tensor_model_parallel_size=2 \
  distillation.teacher_models.teacher_model.inference.data_parallel_size=1 \
  distillation.teacher_models.teacher_model.inference.gpu_memory_utilization=0.85 \
  distillation.teacher_models.teacher_model.inference.enforce_eager=True \
  distillation.teacher_models.teacher_model.inference.max_num_seqs=32 \
  distillation.teacher_models.teacher_model.inference.max_num_batched_tokens=65536 \
  distillation.teacher_models.teacher_model.inference.max_model_len=${MAX_MODEL_LEN} \
  distillation.distillation_loss.loss_mode=k1 \
  distillation.distillation_loss.use_policy_gradient=True \
  distillation.distillation_loss.policy_loss_mode=vanilla \
  distillation.distillation_loss.use_task_rewards=False \
  distillation.distillation_loss.distillation_loss_coef=1.0 \
  distillation.distillation_loss.loss_max_clamp=10.0 \
  distillation.distillation_loss.log_prob_min_clamp=-10.0 \
  "$@"
